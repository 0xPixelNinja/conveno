// Generates src/generated/* from brand/tokens.json, brand/components/terminal-theme.json and
// brand/icons/. Nothing in the output is typed by hand. Run once by the turbo `generate` task, which
// build, typecheck and test depend on. A file whose content is unchanged is not rewritten.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const brand = join(here, "..", "..", "..", "brand");
const out = join(here, "..", "src", "generated");
mkdirSync(out, { recursive: true });

const readJson = (p) => JSON.parse(readFileSync(join(brand, p), "utf8"));
const tokens = readJson("tokens.json");
const theme = readJson("components/terminal-theme.json");
const iconsJson = readJson("icons/icons.json");
const sprite = readFileSync(join(brand, "icons", "sprite.svg"), "utf8");

const HEADER = "// Generated by scripts/generate.mjs from brand/. Do not edit.\n";
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const write = (name, text) => {
  const file = join(out, name);
  if (existsSync(file) && readFileSync(file, "utf8") === text) return;
  writeFileSync(file, text);
};

// tokens.ts, tokens.json
write(
  "tokens.ts",
  `${HEADER}export const tokens = ${JSON.stringify(tokens, null, 2)} as const;\n\nexport type Tokens = typeof tokens;\n`,
);
write("tokens.json", `${JSON.stringify(tokens, null, 2)}\n`);

// terminal-theme.ts: the role table (truecolor, xterm-256 index, 16-colour SGR code)
write(
  "terminal-theme.ts",
  `${HEADER}export const terminalTheme = ${JSON.stringify(theme, null, 2)} as const;\n`,
);

// icon-names.ts
const iconNames = Object.keys(iconsJson).filter((k) => !k.startsWith("_"));
const tuned16 = iconNames.filter((n) => sprite.includes(`id="cv-${n}-16"`));
write(
  "icon-names.ts",
  `${HEADER}export const ICON_NAMES = ${JSON.stringify(iconNames, null, 2)} as const;\n\n` +
    `/** Icons that also have a hand-tuned 16 px symbol (\`cv-<name>-16\`). */\n` +
    `export const ICON_NAMES_WITH_16 = ${JSON.stringify(tuned16, null, 2)} as const;\n`,
);
write("sprite.svg", sprite);

// tokens.css: --cv- custom properties. Light on :root, dark via prefers-color-scheme and
// [data-theme="dark"], following brand/components/components.css.
const decl = (pairs, indent) => pairs.map(([k, v]) => `${indent}--cv-${k}: ${v};`).join("\n");
const colorPairs = (mode) => Object.entries(tokens.color[mode]).map(([k, v]) => [kebab(k), v]);
const px = (n) => (n === 0 ? "0" : `${n}px`);
const base = [
  ...Object.entries(tokens.type).flatMap(([k, v]) =>
    ["display", "body", "mono"].includes(k) ? [[`f-${k}`, `"${v.family}", ${v.fallback}`]] : [],
  ),
  ...Object.entries(tokens.type.scale).map(([k, v]) => [`fs-${k}`, px(v)]),
  ...Object.entries(tokens.type.lineHeight).map(([k, v]) => [`lh-${k}`, String(v)]),
  ...Object.entries(tokens.type.tracking).map(([k, v]) => [`tracking-${k}`, v]),
  ...tokens.space.scale.map((v, i) => [`s-${i}`, px(v)]),
  ...Object.entries(tokens.radius).map(([k, v]) => [
    `r-${kebab(k)}`,
    typeof v === "number" ? px(v) : v,
  ]),
  ...Object.entries(tokens.stroke).map(([k, v]) => [`stroke-${kebab(k)}`, px(v)]),
  ...Object.entries(tokens.motion.ease).map(([k, v]) => [`ease-${k}`, v]),
  ...Object.entries(tokens.motion.duration).map(([k, v]) => [`dur-${k}`, `${v}ms`]),
  ["stagger", `${tokens.motion.stagger}ms`],
];
const derived = [
  ...["entry", "stamp", "ok", "warn", "error", "info"].map((r) => [
    `${r}-tint`,
    tokens.color.derived["tint(x)"].replaceAll("--cv-x", `--cv-${r}`),
  ]),
  ["rule-soft", tokens.color.derived.ruleSoft],
];
const css = `/* Generated by scripts/generate.mjs from brand/tokens.json. Do not edit. */
:root {
  color-scheme: light;
${decl(colorPairs("light"), "  ")}
${decl(base, "  ")}
${decl(derived, "  ")}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${decl(colorPairs("dark"), "    ")}
  }
}
:root[data-theme="dark"] {
  color-scheme: dark;
${decl(colorPairs("dark"), "  ")}
}
`;
write("tokens.css", css);
console.log("brand: generated", iconNames.length, "icons,", base.length + derived.length, "tokens");
